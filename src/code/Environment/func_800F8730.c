#include "generated/mm/z_kankyo.h"

void Environment_UpdateCheckedPostboxes(void) {
    if (!CHECK_WEEKEVENTREG(WEEKEVENTREG_POSTMAN_CHECKED_SOUTH_UPPER_CLOCKTOWN) &&
        (SCRIPT_TIME_NOW >= SCRIPT_TIME(9, 31))) {
        SET_WEEKEVENTREG(WEEKEVENTREG_POSTMAN_CHECKED_SOUTH_UPPER_CLOCKTOWN);
        Environment_SetLetterToKafeiScheduledIf(WEEKEVENTREG_DEPOSITED_LETTER_TO_KAFEI_SOUTH_UPPER_CLOCKTOWN);
    }

    if (!CHECK_WEEKEVENTREG(WEEKEVENTREG_POSTMAN_CHECKED_NORTH_CLOCKTOWN) && (SCRIPT_TIME_NOW >= SCRIPT_TIME(10, 3))) {
        SET_WEEKEVENTREG(WEEKEVENTREG_POSTMAN_CHECKED_NORTH_CLOCKTOWN);
        Environment_SetLetterToKafeiScheduledIf(WEEKEVENTREG_DEPOSITED_LETTER_TO_KAFEI_NORTH_CLOCKTOWN);
    }

    if (!CHECK_WEEKEVENTREG(WEEKEVENTREG_POSTMAN_CHECKED_EAST_UPPER_CLOCKTOWN) &&
        (SCRIPT_TIME_NOW >= SCRIPT_TIME(10, 35))) {
        SET_WEEKEVENTREG(WEEKEVENTREG_POSTMAN_CHECKED_EAST_UPPER_CLOCKTOWN);
        Environment_SetLetterToKafeiScheduledIf(WEEKEVENTREG_DEPOSITED_LETTER_TO_KAFEI_EAST_UPPER_CLOCKTOWN);
    }

    if (!CHECK_WEEKEVENTREG(WEEKEVENTREG_POSTMAN_CHECKED_EAST_LOWER_CLOCKTOWN) &&
        (SCRIPT_TIME_NOW >= SCRIPT_TIME(10, 53))) {
        SET_WEEKEVENTREG(WEEKEVENTREG_POSTMAN_CHECKED_EAST_LOWER_CLOCKTOWN);
        Environment_SetLetterToKafeiScheduledIf(WEEKEVENTREG_DEPOSITED_LETTER_TO_KAFEI_EAST_LOWER_CLOCKTOWN);
    }

    if (!CHECK_WEEKEVENTREG(WEEKEVENTREG_POSTMAN_CHECKED_SOUTH_LOWER_CLOCKTOWN) &&
        (SCRIPT_TIME_NOW >= SCRIPT_TIME(11, 25))) {
        SET_WEEKEVENTREG(WEEKEVENTREG_POSTMAN_CHECKED_SOUTH_LOWER_CLOCKTOWN);
        Environment_SetLetterToKafeiScheduledIf(WEEKEVENTREG_DEPOSITED_LETTER_TO_KAFEI_SOUTH_LOWER_CLOCKTOWN);
    }
}
